"""
train_model_uci_tensorflow.py
------------------------------
The TensorFlow / TinyML leg of the UCI pipeline:
    Keras model -> int8-quantized TensorFlow Lite -> C array (model.h)

It re-uses the SAME cleaned data, the SAME week-block split and the SAME
network shape that train_model_uci.py selected, so the two are comparable.
It measures the quantized .tflite on the test weeks (not just the float
Keras model) - that number is the honest one to report, because the
quantized model is what would actually run on a microcontroller.

Run train_model_uci.py first (it writes models/uci/model_uci.json with the
chosen hyper-parameters), then:

    pip install tensorflow scikit-learn pandas numpy
    python train_model_uci_tensorflow.py

Outputs (models/uci/eloquenttinyml/):
    iaq_uci.keras, iaq_uci.tflite, model.h, normalization.h, tflite_report.json

IMPORTANT: the inputs here are the UCI dataset's sensor array (T, RH and five
PT08 metal-oxide sensors), not a DHT22 + MQ-135. This model cannot be dropped
into the DHT22/MQ-135 sketches; see README.md ("Real-data model").
"""

import json
import os

os.environ.setdefault("TF_CPP_MIN_LOG_LEVEL", "2")

import numpy as np
import tensorflow as tf
from sklearn.metrics import (accuracy_score, classification_report, confusion_matrix,
                             precision_recall_fscore_support)

import prepare_uci_dataset as P

OUT_DIR = os.path.join(P.HERE, "models", "uci", "eloquenttinyml")
SEED = 42


def build(n_in, hidden, n_out):
    layers = [tf.keras.layers.Input(shape=(n_in,))]
    layers += [tf.keras.layers.Dense(h, activation="relu") for h in hidden]
    layers += [tf.keras.layers.Dense(n_out, activation="softmax")]
    m = tf.keras.Sequential(layers)
    m.compile(optimizer=tf.keras.optimizers.Adam(1e-3), loss="sparse_categorical_crossentropy", metrics=["accuracy"])
    return m


def macro(y, pred):
    p, r, f, _ = precision_recall_fscore_support(y, pred, average="macro", zero_division=0)
    return {"accuracy": float(accuracy_score(y, pred)), "precision_macro": float(p),
            "recall_macro": float(r), "f1_macro": float(f)}


def run_tflite(tflite_bytes, X):
    try:  # newer TensorFlow moves the interpreter to the standalone LiteRT package
        from ai_edge_litert.interpreter import Interpreter
    except ImportError:
        Interpreter = tf.lite.Interpreter
    interp = Interpreter(model_content=tflite_bytes)
    interp.allocate_tensors()
    inp, out = interp.get_input_details()[0], interp.get_output_details()[0]
    probs = np.zeros((len(X), out["shape"][-1]), dtype=np.float32)
    for i in range(len(X)):
        interp.set_tensor(inp["index"], X[i:i + 1].astype(np.float32))
        interp.invoke()
        probs[i] = interp.get_tensor(out["index"])[0]
    return probs


def write_c_array(data, path, var):
    with open(path, "w") as f:
        f.write("// AUTO-GENERATED by train_model_uci_tensorflow.py - do not hand-edit.\n#pragma once\n\n")
        f.write(f"const unsigned int {var}_len = {len(data)};\nalignas(8) const unsigned char {var}[] = {{\n")
        for i in range(0, len(data), 12):
            f.write("  " + ", ".join(f"0x{b:02x}" for b in data[i:i + 12]) + ",\n")
        f.write("};\n")


def main():
    with open(os.path.join(P.HERE, "models", "uci", "model_uci.json")) as f:
        chosen = json.load(f)["config"]
    hidden = tuple(chosen["hidden"])
    print(f"Using network shape chosen by train_model_uci.py: hidden layers {hidden}")

    df = P.load_clean()
    X = df[P.FEATURES].to_numpy(dtype=np.float32)
    y = df["label"].to_numpy(dtype=np.int64)
    tr, va, te = P.week_block_split(df)
    mean, std = X[tr].mean(0), X[tr].std(0)
    std[std == 0] = 1
    Xn = ((X - mean) / std).astype(np.float32)

    # 5 random initialisations; keep the best on VALIDATION loss (never on test)
    best, best_vl = None, np.inf
    for s in range(5):
        tf.keras.utils.set_random_seed(SEED + s)
        m = build(len(P.FEATURES), hidden, len(P.LABEL_NAMES))
        h = m.fit(Xn[tr], y[tr], validation_data=(Xn[va], y[va]), epochs=300, batch_size=64, verbose=0,
                  callbacks=[tf.keras.callbacks.EarlyStopping(patience=20, restore_best_weights=True)])
        vl = min(h.history["val_loss"])
        print(f"  init {s}: best val loss {vl:.4f} ({len(h.history['loss'])} epochs run)")
        if vl < best_vl:
            best, best_vl = m, vl
    model = best

    p_float = model.predict(Xn[te], verbose=0)
    res = {"hidden": list(hidden), "keras_float_test": macro(y[te], p_float.argmax(1))}

    # ---- int8 quantization (float in / float out) ----
    def rep_data():
        for i in range(min(500, tr.sum())):
            yield [Xn[tr][i:i + 1]]

    conv = tf.lite.TFLiteConverter.from_keras_model(model)
    conv.optimizations = [tf.lite.Optimize.DEFAULT]
    conv.representative_dataset = rep_data
    conv.target_spec.supported_ops = [tf.lite.OpsSet.TFLITE_BUILTINS_INT8]
    conv.inference_input_type = tf.float32
    conv.inference_output_type = tf.float32
    tflite = conv.convert()

    conv32 = tf.lite.TFLiteConverter.from_keras_model(model)
    size_fp32 = len(conv32.convert())

    p_q = run_tflite(tflite, Xn[te])
    res["tflite_int8_test"] = macro(y[te], p_q.argmax(1))
    res["tflite_bytes_int8"] = len(tflite)
    res["tflite_bytes_float32"] = size_fp32
    res["agreement_float_vs_int8"] = float(np.mean(p_float.argmax(1) == p_q.argmax(1)))
    res["confusion_matrix_int8"] = confusion_matrix(y[te], p_q.argmax(1), labels=range(3)).tolist()

    os.makedirs(OUT_DIR, exist_ok=True)
    model.save(os.path.join(OUT_DIR, "iaq_uci.keras"))
    with open(os.path.join(OUT_DIR, "iaq_uci.tflite"), "wb") as f:
        f.write(tflite)
    write_c_array(tflite, os.path.join(OUT_DIR, "model.h"), "iaq_model_tflite")
    with open(os.path.join(OUT_DIR, "normalization.h"), "w") as f:
        f.write("// AUTO-GENERATED. Inputs, in order: " + ", ".join(P.FEATURES) + "\n#pragma once\n")
        f.write(f"#define IAQ_N_FEATURES {len(P.FEATURES)}\n")
        f.write("static const float iaq_feature_mean[IAQ_N_FEATURES] = {" + ", ".join(f"{v:.6f}f" for v in mean) + "};\n")
        f.write("static const float iaq_feature_std[IAQ_N_FEATURES]  = {" + ", ".join(f"{v:.6f}f" for v in std) + "};\n")
        f.write('static const char* iaq_class_names[3] = {"Good", "Moderate", "Poor"};\n')
    with open(os.path.join(OUT_DIR, "tflite_report.json"), "w") as f:
        json.dump(res, f, indent=2)

    print("\n=========== TEST WEEKS ===========")
    for k in ("keras_float_test", "tflite_int8_test"):
        v = res[k]
        print(f"{k:18s} acc {v['accuracy']:.4f}  macro-P {v['precision_macro']:.4f}  "
              f"macro-R {v['recall_macro']:.4f}  macro-F1 {v['f1_macro']:.4f}")
    print(f"float32 .tflite: {size_fp32} bytes   int8 .tflite: {len(tflite)} bytes")
    print(f"float-vs-int8 prediction agreement: {res['agreement_float_vs_int8']:.4f}")
    print("int8 confusion matrix (Good/Moderate/Poor):")
    print(np.array(res["confusion_matrix_int8"]))
    print(classification_report(y[te], p_q.argmax(1), target_names=P.LABEL_NAMES, zero_division=0))


if __name__ == "__main__":
    main()
